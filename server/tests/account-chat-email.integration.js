test('account recovery, match outbox and private realtime chat on real MySQL', { timeout: 120000 }, async t => {
  const base = configFromEnv(), name = `findit_test_${randomBytes(12).toString('hex')}`;
  const connection = await connect(base, false);
  let pool, server, io, chat;
  const sockets = [];
  const password = 'Initial-password123';
  try {
    await connection.query(`CREATE DATABASE ${quote(name)} CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci`);
    await connection.query(`USE ${quote(name)}`);
    await migrate(connection, name);
    await connection.query("INSERT INTO roles (name) VALUES ('USER'),('ADMIN')");
    pool = createDbPool({ ...base, database: name });
    const users = createUserRepository(pool), tokens = createTokenService({ secret: randomBytes(32).toString('hex'), expiresIn: 3600 });
    const auth = createAuthService(users, tokens);
    const accounts = [];
    for (let i = 0; i < 3; i++) accounts.push(await auth.register({ fullName: `Người ${i}`, email: `person${i}@test.example`, password }));
    let jwtA = (await auth.login({ email: accounts[0].email, password })).token;
    const jwtB = (await auth.login({ email: accounts[1].email, password })).token, jwtC = (await auth.login({ email: accounts[2].email, password })).token;
    const sent = [];
    const mailer = createMailer({ RESEND_API_KEY: 'integration-test-only', EMAIL_FROM: 'FindIt <sender@findit.example>', FRONTEND_URL: 'https://findit.example' }, async (url, options) => {
      assert.equal(url, 'https://api.resend.com/emails');
      sent.push(JSON.parse(options.body));
      return Response.json({ id: randomUUID() });
    });
    const reset = createPasswordResetService(pool, mailer, id => { for (const s of io.sockets.sockets.values()) if (s.data.identity.id === id) s.disconnect(true); });
    chat = createChatService(createChatRepository(pool));
    const app = express();
    if (process.env.FINDIT_FEATURE_BROWSER === '1') {
      const root = fileURLToPath(new URL('../../client/dist/', import.meta.url));
      app.use(express.static(root));
      app.use((req, res, next) => req.path.startsWith('/api/') ? next() : res.sendFile(root + '/index.html'));
    }
    app.use(createApp({ healthService: { check: async () => ({}) }, authService: auth, userService: createUserService(users), passwordResetService: reset, chatService: chat, logger: () => {} }));
    server = createServer(app);
    const corsOrigins = ['https://findit.example'];
    io = attachChatSocket(server, { authService: auth, chatService: chat, corsOrigins });
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const http = { url: `http://127.0.0.1:${server.address().port}` };
    corsOrigins.push(http.url);
    const socket = async token => {
      const s = connectSocket(http.url, { auth: { token }, autoConnect: false, transports: ['websocket'], reconnection: false });
      sockets.push(s); const ready = once(s, 'connect', { signal: AbortSignal.timeout(5000) }); s.connect(); await ready; return s;
    };
    let a, b, conversation;
    await t.test('conversation uniqueness, member authorization, persistence, retry, cursor and unread state', async () => {
      const response = await request(http, '/api/conversations', { method: 'POST', token: jwtA, body: { userId: accounts[1].id } });
      assert.equal(response.status, 201); conversation = response.json.data.id;
      const duplicates = await Promise.all(Array.from({ length: 5 }, () => chat.create({ id: String(accounts[1].id) }, { userId: accounts[0].id })));
      assert.ok(duplicates.every(row => row.id === conversation));
      assert.equal((await request(http, '/api/conversations', { method: 'POST', token: jwtA, body: { userId: accounts[0].id } })).status, 400);
      assert.equal((await request(http, `/api/conversations/${conversation}/messages`, { token: jwtC })).status, 404);
      assert.equal((await request(http, `/api/conversations/${conversation}/messages`)).status, 401);
      a = await socket(jwtA); b = await socket(jwtB);
      const outsider = await socket(jwtC);
      assert.equal((await outsider.timeout(3000).emitWithAck('conversation:join', { conversationId: conversation })).success, false);
      assert.equal((await outsider.timeout(3000).emitWithAck('message:send', { conversationId: conversation, clientId: randomUUID(), content: 'not allowed' })).success, false);
      const received = once(b, 'message:new', { signal: AbortSignal.timeout(5000) });
      const body = { conversationId: conversation, clientId: randomUUID(), content: '<img src=x onerror=alert(1)>' };
      const result = await a.timeout(5000).emitWithAck('message:send', body);
      assert.equal(result.success, true); assert.equal((await received)[0].content, body.content);
      const retry = await a.timeout(5000).emitWithAck('message:send', body);
      assert.equal(retry.data.id, result.data.id);
      assert.equal((await chat.history({ id: String(accounts[1].id) }, conversation, {})).length, 1);
      assert.equal((await chat.unread({ id: String(accounts[1].id) })).unreadCount, 1);
      assert.equal((await chat.history({ id: String(accounts[1].id) }, conversation, { before: result.data.id })).length, 0);
      await b.timeout(3000).emitWithAck('message:read', { conversationId: conversation, messageId: result.data.id });
      assert.equal((await chat.unread({ id: String(accounts[1].id) })).unreadCount, 0);
      b.disconnect();
      const missed = await chat.send({ id: String(accounts[0].id) }, conversation, { clientId: randomUUID(), content: 'While offline' });
      b = await socket(jwtB);
      const sync = await chat.history({ id: String(accounts[1].id) }, conversation, { after: result.data.id });
      assert.equal(sync[0].id, missed.id);
      const parallelBody = { clientId: randomUUID(), content: 'Concurrent retries' };
      const concurrent = await Promise.all([1, 2].map(() => chat.send({ id: String(accounts[0].id) }, conversation, parallelBody)));
      assert.equal(concurrent[0].id, concurrent[1].id);
    });
    await t.test('forgot responses, account throttle, hash-only storage, expiration, atomic consumption and session invalidation', async () => {
      const existing = await request(http, '/api/auth/forgot-password', { method: 'POST', body: { email: accounts[0].email } });
      const absent = await request(http, '/api/auth/forgot-password', { method: 'POST', body: { email: 'absent@test.example' } });
      assert.equal(existing.status, absent.status); assert.deepEqual(existing.json, absent.json);
      assert.equal(sent.length, 1);
      await reset.forgot({ email: accounts[0].email }); assert.equal(sent.length, 1);
      const token = sent[0].text.match(/#token=([a-f0-9]{64})/)[1];
      const [[record]] = await query(pool, 'SELECT * FROM password_reset_tokens WHERE user_id=?', [accounts[0].id]);
      assert.equal(record.token_hash, hashResetToken(token)); assert.ok(!JSON.stringify(record).includes(token));
      assert.equal(Math.round((record.expires_at - record.created_at) / 60000), 15);
      await assert.rejects(() => reset.reset({ token: 'a'.repeat(64), password: 'New-password123' }), e => e.status === 400);
      const disconnected = once(a, 'disconnect', { signal: AbortSignal.timeout(5000) });
      const attempts = await Promise.allSettled([1, 2].map(() => reset.reset({ token, password: 'New-password123' })));
      assert.equal(attempts.filter(r => r.status === 'fulfilled').length, 1);
      assert.equal(attempts.find(r => r.status === 'rejected').reason.status, 400);
      await disconnected;
      await assert.rejects(() => auth.authenticate(jwtA), e => e.status === 401);
      assert.equal((await request(http, '/api/conversations/unread-count', { token: jwtA })).status, 401);
      await assert.rejects(() => reset.reset({ token, password: 'New-password123' }), e => e.status === 400);
      jwtA = (await auth.login({ email: accounts[0].email, password: 'New-password123' })).token;
      assert.equal((await auth.authenticate(jwtA)).id, String(accounts[0].id));
      await reset.forgot({ email: accounts[0].email });
      const expired = sent.at(-1).text.match(/#token=([a-f0-9]{64})/)[1];
      await query(pool, 'UPDATE password_reset_tokens SET expires_at=DATE_SUB(UTC_TIMESTAMP(),INTERVAL 1 SECOND) WHERE user_id=?', [accounts[0].id]);
      await assert.rejects(() => reset.reset({ token: expired, password: 'Another-password123' }), e => e.status === 400);
      const disabled = createPasswordResetService(pool, { configured: false });
      for (const email of [accounts[0].email, 'absent@test.example']) await assert.rejects(() => disabled.forgot({ email }), e => e.status === 503);
      const failing = createPasswordResetService(pool, { ...mailer, send: async () => { throw new Error('Resend failed'); } });
      const failure = await failing.forgot({ email: accounts[2].email });
      assert.equal(failure, absent.json.message);
      const [[failedToken]] = await query(pool, 'SELECT expires_at<=UTC_TIMESTAMP() AS expired FROM password_reset_tokens WHERE user_id=?', [accounts[2].id]);
      assert.equal(Number(failedToken.expired), 1);
    });
    await t.test('threshold edges, unique recipients, no backfill, Resend retries, competing workers and expired leases', async () => {
      await query(pool, "INSERT INTO categories (name) VALUES ('Test')"); await query(pool, "INSERT INTO locations (name) VALUES ('Test')");
      for (const [i, type] of ['LOST', 'FOUND'].entries()) await query(pool, "INSERT INTO items (user_id,category_id,location_id,title,description,type,event_date,created_at,updated_at) VALUES (?,1,1,?,'text',?,'2026-11-05',UTC_TIMESTAMP(),UTC_TIMESTAMP())", [accounts[i].id, `Item ${i}`, type]);
      const [[count]] = await query(pool, 'SELECT COUNT(*) AS n FROM email_outbox'); assert.equal(Number(count.n), 0);
      const save = score => transaction(pool, async c => {
        const repository = createMatchingRepository(pool, (sql, values = []) => c.query({ sql, timeout: databaseTimeout }, values));
        const result = await repository.save('1', '2', { score, reasons: [] });
        if (result.created) await repository.notifyNewMatch(result.matchId, '1', '2');
      });
      await save(49);
      assert.equal((await query(pool, 'SELECT * FROM email_outbox'))[0].length, 0);
      await save(50); await save(80); await save(49); await save(100);
      const [jobs] = await query(pool, 'SELECT * FROM email_outbox ORDER BY user_id');
      assert.equal(jobs.length, 2); assert.deepEqual(jobs.map(row => Number(row.user_id)), accounts.slice(0, 2).map(user => user.id));
      assert.equal((await query(pool, "SELECT * FROM notifications WHERE type='NEW_MATCH'"))[0].length, 2);
      const failing = createEmailWorker(pool, { ...mailer, send: async () => { throw Object.assign(new Error('private provider detail'), { code: 'RESEND_RATE_LIMIT', retryAfter: 90 }); } });
      await failing.tick();
      const [[failed]] = await query(pool, 'SELECT * FROM email_outbox WHERE job_id=?', [jobs[0].job_id]);
      assert.equal(failed.status, 'PENDING'); assert.equal(failed.attempts, 1); assert.equal(failed.last_error, 'RESEND_RATE_LIMIT');
      assert.ok(failed.next_attempt_at - failed.created_at >= 90000);
      await query(pool, "UPDATE email_outbox SET next_attempt_at=UTC_TIMESTAMP(),status='PROCESSING',lease_until=DATE_SUB(UTC_TIMESTAMP(),INTERVAL 1 SECOND),lease_token=? WHERE job_id=?", [randomUUID(), jobs[0].job_id]);
      const delivered = [], good = createEmailWorker(pool, { ...mailer, send: async mail => { delivered.push(mail); } });
      await Promise.all([good.tick(), good.tick()]);
      assert.equal(delivered.length, 2); assert.equal((await query(pool, "SELECT * FROM email_outbox WHERE status='SENT'"))[0].length, 2);
      await good.tick(); assert.equal(delivered.length, 2);
      await query(pool, "UPDATE email_outbox SET status='PROCESSING',attempts=5,lease_until=DATE_SUB(UTC_TIMESTAMP(),INTERVAL 1 SECOND) WHERE job_id=?", [jobs[0].job_id]);
      await good.tick();
      assert.equal((await query(pool, 'SELECT status FROM email_outbox WHERE job_id=?', [jobs[0].job_id]))[0][0].status, 'FAILED');
      await query(pool, "UPDATE email_outbox SET status='PENDING',attempts=0,next_attempt_at=UTC_TIMESTAMP() WHERE job_id=?", [jobs[1].job_id]);
      await createEmailWorker(pool, { ...mailer, send: async () => { throw Object.assign(new Error('private auth response'), { code: 'RESEND_AUTH', permanent: true }); } }).tick();
      const [[rejected]] = await query(pool, 'SELECT status,attempts,last_error FROM email_outbox WHERE job_id=?', [jobs[1].job_id]);
      assert.equal(rejected.status, 'FAILED'); assert.equal(rejected.attempts, 1); assert.equal(rejected.last_error, 'RESEND_AUTH');
    });
    if (process.env.FINDIT_FEATURE_BROWSER === '1') await t.test('desktop and mobile account/chat UI in Chrome', async () => {
      const { featureBrowserCheck } = await import('../../client/scripts/feature-browser-check.mjs');
      await featureBrowserCheck({ url: http.url, emailA: accounts[0].email, emailB: accounts[1].email, passwordA: 'New-password123', passwordB: password, conversation, reset, pool, query, sent });
    });
    await t.test('password recovery limits requests before sending email', async () => {
      let limited = false;
      for (let i = 0; i < 10; i++) { const response = await request(http, '/api/auth/forgot-password', { method: 'POST', body: { email: 'absent@test.example' } }); if (response.status === 429) limited = true; }
      assert.equal(limited, true);
    });
  } finally {
    for (const socket of sockets) socket.disconnect();
    chat?.close();
    if (io) await new Promise(resolve => io.close(resolve));
    if (server?.listening) await new Promise(resolve => server.close(resolve));
    await pool?.end();
    if (!/^findit_test_[a-f0-9]{24}$/.test(name)) throw new Error('Unowned database');
    await connection.query(`DROP DATABASE ${quote(name)}`);
    await connection.end();
  }
});
