CREATE TABLE `reports` (
  `report_id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `reporter_id` BIGINT UNSIGNED NOT NULL,
  `target_type` ENUM('ITEM','USER','CLAIM') NOT NULL,
  `item_id` BIGINT UNSIGNED NULL,
  `reported_user_id` BIGINT UNSIGNED NULL,
  `claim_id` BIGINT UNSIGNED NULL,
  `reason` VARCHAR(50) NOT NULL,
  `description` TEXT NULL,
  `status` ENUM('PENDING','REVIEWING','RESOLVED','DISMISSED') NOT NULL DEFAULT 'PENDING',
  `reviewed_by` BIGINT UNSIGNED NULL,
  `reviewed_at` DATETIME NULL,
  `created_at` DATETIME NOT NULL,
  PRIMARY KEY (`report_id`),
  KEY `idx_reports_reporter_id` (`reporter_id`),
  KEY `idx_reports_item_id` (`item_id`),
  KEY `idx_reports_reported_user_id` (`reported_user_id`),
  KEY `idx_reports_claim_id` (`claim_id`),
  KEY `idx_reports_reviewed_by` (`reviewed_by`),
  CONSTRAINT `fk_reports_reporter` FOREIGN KEY (`reporter_id`) REFERENCES `users` (`user_id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `fk_reports_item` FOREIGN KEY (`item_id`) REFERENCES `items` (`item_id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `fk_reports_user` FOREIGN KEY (`reported_user_id`) REFERENCES `users` (`user_id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `fk_reports_claim` FOREIGN KEY (`claim_id`) REFERENCES `claims` (`claim_id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `fk_reports_reviewer` FOREIGN KEY (`reviewed_by`) REFERENCES `users` (`user_id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `ck_reports_target` CHECK ((target_type = 'ITEM' AND item_id IS NOT NULL AND reported_user_id IS NULL AND claim_id IS NULL) OR (target_type = 'USER' AND item_id IS NULL AND reported_user_id IS NOT NULL AND claim_id IS NULL) OR (target_type = 'CLAIM' AND item_id IS NULL AND reported_user_id IS NULL AND claim_id IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
