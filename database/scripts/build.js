import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { tables, metadata, createTable } from '../schema.js';

const root = new URL('../', import.meta.url);
await mkdir(new URL('migrations/', root), { recursive: true });
const statements = [];
for (const [index, table] of tables.entries()) {
  const sql = createTable(table);
  const name = `${String(index + 1).padStart(3, '0')}_${table.name}.sql`;
  await writeFile(new URL(`migrations/${name}`, root), sql);
  statements.push(sql);
}
await writeFile(new URL('database-schema.sql', root),
  '-- Generated by npm run db:build. Runtime migrations use the same definitions.\n' +
  '-- Only import into an empty database; this file does not adopt migration history.\n' +
  "CREATE DATABASE IF NOT EXISTS `findit_db` CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;\n" +
  'USE `findit_db`;\nSET time_zone = \'+00:00\';\n\n' + createTable(metadata) + '\n' + statements.join('\n'));
console.log(`Generated ${tables.length} migrations and ${fileURLToPath(new URL('database-schema.sql', root))}`);
